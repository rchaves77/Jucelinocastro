const LOCAL_STORAGE_KEY = 'jc_patient_testimonials_real_v3';

export const getStoredTestimonials = (): Testimonial[] => {
  try {
    const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Error loading testimonials', e);
  }
  return INITIAL_TESTIMONIALS;
};

export const saveNewTestimonial = (newTestimonial: Omit<Testimonial, 'id' | 'date' | 'verifiedPatient' | 'avatarInitial'> & { source?: 'google' | 'doctoralia' | 'whatsapp' | 'site' }): Testimonial => {
  const current = getStoredTestimonials();
  const created: Testimonial = {
    ...newTestimonial,
    id: `test-${Date.now()}`,
    date: 'Recentemente (Verificação Concluída)',
    verifiedPatient: true,
    avatarInitial: newTestimonial.name.trim().charAt(0).toUpperCase() || 'P',
    source: newTestimonial.source || 'site',
  };
  const updated = [created, ...current];
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(updated));
  } catch (e) {
    console.error('Error saving testimonial', e);
  }
  return created;
};

export type UserRole = 'admin' | 'physio' | 'secretary';
export type UserStatus = 'active' | 'pending' | 'rejected';

export interface User {
  id: string;
  name: string;
  email: string;
  role: UserRole;
  password?: string;
  avatarUrl?: string;
  specialty?: string;
  crefito?: string;
  phone?: string;
  status?: UserStatus;
  createdAt?: string;
}

export interface AttendanceCertificate {
  id: string; // Hash identifier e.g. "JC-DECL-2026-9814"
  patientId: string;
  patientName: string;
  patientCpf: string;
  appointmentDate: string; // YYYY-MM-DD
  timeSlot: string;
  physioName: string;
  physioCrefito?: string;
  receptionistName: string;
  issuedAt: string;
  clinicName: string;
  validationUrl: string;
  status: 'valid' | 'revoked';
}

export interface ExamAttachment {
  id: string;
  title: string;
  date: string;
  thumbnailUrl: string;
  fullUrl: string;
  category: 'Raio-X' | 'Ressonância' | 'Ultrassom' | 'Laudo' | 'Foto';
  notes?: string;
}

export interface Anamnesis {
  mainComplaint: string;
  illnessHistory: string;
  painScale: number; // 0-10
  physicalExam: string;
  postureAnalysis: string;
  treatmentPlan: string;
  goals: string;
  clinicalObs: string;
  lastUpdated: string;
}

export interface Evolution {
  id: string;
  date: string;
  physioName: string;
  description: string;
  painScaleBefore: number;
  painScaleAfter: number;
  procedures: string[];
  nextSessionGoals: string;
  isDraft?: boolean;
  receptionAutoGenerated?: boolean;
  lastUpdated?: string;
  lastEditedBy?: string;
}

export interface EvolutionTemplate {
  id: string;
  title: string;
  category: string;
  description: string;
  procedures: string[];
  painScaleBefore: number;
  painScaleAfter: number;
  nextSessionGoals: string;
  createdAt: string;
  createdBy?: string;
}

export interface AuditLog {
  id: string;
  timestamp: string;
  authorName: string;
  authorRole: UserRole;
  action: string;
  details: string;
  targetPatientName?: string;
  targetPatientId?: string;
  module: 'Atendimento/Recepção' | 'Prontuário' | 'Templates' | 'Equipe' | 'Agenda';
}

export interface Patient {
  id: string;
  name: string;
  cpf: string;
  phone: string;
  email: string;
  birthDate: string;
  gender: 'Masculino' | 'Feminino' | 'Outro';
  address: string;
  photoUrl: string;
  status: 'Ativo' | 'Em Pausa' | 'Alta';
  assignedPhysioId: string;
  assignedPhysioName: string;
  mainComplaint: string;
  anamnesis: Anamnesis;
  evolutions: Evolution[];
  exams: ExamAttachment[];
  createdAt: string;
}

export type AppointmentStatus = 'confirmed' | 'in_progress' | 'completed' | 'canceled' | 'no_show' | 'pending';
export type AppointmentType = 'Avaliação' | 'Sessão' | 'Pilates' | 'Retorno' | 'RPG' | 'Quiropraxia';

export interface Appointment {
  id: string;
  patientId: string;
  patientName: string;
  patientPhone: string;
  patientPhoto?: string;
  physioId: string;
  physioName: string;
  date: string; // YYYY-MM-DD
  timeSlot: string; // HH:mm (e.g., "08:00")
  status: AppointmentStatus;
  type: AppointmentType;
  room: string;
  notes?: string;
  price: number;
  inProgressAt?: string; // ISO timestamp when status changed to in_progress
  isEncaixe?: boolean; // Flag to indicate if appointment is an encaixe in the same slot
}

export interface ChatMessage {
  id: string;
  senderId: string;
  senderName: string;
  senderRole: UserRole;
  senderAvatar?: string;
  content: string;
  timestamp: string;
  isInternal?: boolean;
}

export interface ClinicMetrics {
  totalPatients: number;
  activePatients: number;
  monthlyRevenue: number;
  attendanceRate: number; // Percentage (e.g., 94)
  monthlyAppointments: number;
  topTreatments: { name: string; count: number }[];
}

export type TaskPriority = 'baixa' | 'media' | 'alta' | 'urgente';
export type TaskStatus = 'pendente' | 'em_andamento' | 'concluida';

export interface ClinicTask {
  id: string;
  title: string;
  description: string;
  assignedToUserId: string; // User ID or 'all' or 'secretary' or specific physio ID
  assignedToUserName: string;
  assignedByUserId: string;
  assignedByUserName: string;
  priority: TaskPriority;
  status: TaskStatus;
  dueDate?: string; // YYYY-MM-DD
  dueTime?: string; // HH:mm
  patientId?: string;
  patientName?: string;
  createdAt: string;
  completedAt?: string;
  notifyAssigned: boolean;
}

export interface ClinicNotification {
  id: string;
  title: string;
  message: string;
  timestamp: string;
  read: boolean;
  type: 'task' | 'appointment' | 'confirmation' | 'system' | 'patient';
  targetUserId?: string; // If targeting specific user or undefined for all
  linkTab?: string;
  actionUrl?: string;
}
